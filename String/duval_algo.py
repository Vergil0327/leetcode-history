"""
===================================================================
            Duval 雙指標算法原理 (最小循環移位)
===================================================================

【核心思想】
利用已比對成功的相同前綴，進行批量區間剪枝 (Batch Elimination)。
能在 O(N) 線性時間內找出字典序最小的循環旋轉，避免 O(N^2) 的暴力比對。


【演算法運作機制】
將原字串 S (長度 N) 複製兩份接在一起，形成 S' = S + S (長度 2N)。
維護三個指標：
- i：當前候選起點 A (初始為 0)
- j：當前候選起點 B (初始為 1)
- k：從 i 與 j 開始已匹配成功的共同前綴長度 (初始為 0)

比對 S'[i + k] 與 S'[j + k] 的字元：

1. 若 S'[i + k] == S'[j + k]：
- 兩邊前綴字元相同，繼續比較下一個字元。
- k 增加 1 (k = k + 1)。

2. 若 S'[i + k] > S'[j + k]：
- 起點 i 開始的字串在第 k 個字元輸給了起點 j。
- 剪枝：起點 i 淘汰，且 i 到 i + k 之間的所有索引都不可能是最小起點。
- i 直接大跳躍：i = i + k + 1。
- 若跳躍後 i == j，則 j 順延 (j = j + 1)，並將 k 重置為 0。

3. 若 S'[i + k] < S'[j + k]：
- 對稱情況，起點 j 輸給了起點 i。
- j 直接大跳躍：j = j + k + 1。
- 若跳躍後 i == j，則 j 順延 (j = j + 1)，並將 k 重置為 0。

當 i >= N 或 j >= N 或 k >= N 時終止，min(i, j) 即為最小循環移位的起始索引。


【核心數學直覺：為何能一次跳過一整段？】
當比對到位置 k 發現 S'[i + k] > S'[j + k] 時：
表示 S'[i ... i+k-1] 與 S'[j ... j+k-1] 完全相同。

對於介於 [i, i + k] 之間的任意偏移行 p (0 <= p <= k)：
從 i + p 出發的字串前綴，與從 j + p 出發的字串前綴完全相同。
然而在第 k 個字元比較時，依然有 S'[(i+p) + (k-p)] > S'[(j+p) + (k-p)]。

這代表：對於 i 到 i+k 中的每一個起點，都存在一個更優的起點 j + p 壓制著它。
因此，[i, i+k] 這一整段起點都可以被安全地一次性淘汰！


【範例說明】
S = "bba", S' = "bbabba", N = 3

1. i = 0, j = 1, k = 0:
- 比對 S'[0]('b') 與 S'[1]('b') -> 相等 -> k 增為 1。

2. i = 0, j = 1, k = 1:
- 比對 S'[1]('b') 與 S'[2]('a') -> S'[1] > S'[2]。
- 起點 i=0 輸了！索引 0, 1 被一次淘汰。
- i 跳躍至 0 + 1 + 1 = 2。
- 重置 k = 0 (目前 i = 2, j = 1)。

3. i = 2, j = 1, k = 0:
- 比對 S'[2]('a') 與 S'[1]('b') -> S'[2] < S'[1]。
- 起點 j=1 輸了！j 跳躍至 1 + 0 + 1 = 2。
- 此時 i = 2, j = 2 重疊，j 順延至 3，重置 k = 0。

4. 終止條件：j = 3 >= N，演算法結束。
- 最佳起點為 min(2, 3) = 2，對應子字串 "abb"。


【複雜度分析】
- 時間複雜度：O(N)
指標 i 與 j 單調向右移動，總比較次數不超過 4N 次。
- 空間複雜度：O(N)
儲存 S' = S + S 的雙倍字串空間（若用取模運算 % N 可降至 O(1)）。
"""
def get_min_cyclic_rotation(s: str) -> str:
    n = len(s)
    if n <= 1: return s
    
    # Duval 雙指標演算法求字典序最小的循環旋轉
    s_dup = s + s
    i, j, k = 0, 1, 0
    
    while i < n and j < n and k < n:
        if s_dup[i + k] == s_dup[j + k]:
            k += 1
        else:
            if s_dup[i + k] > s_dup[j + k]:
                i += k + 1
            else:
                j += k + 1
            if i == j:
                j += 1
            k = 0
            
    start = min(i, j)
    return s_dup[start:start + n]
